import { Component, OnInit, OnDestroy, EventEmitter, Output } from '@angular/core';
import { ChatService, Conversation } from '../services/chat.service';
import { AgentService, Agent } from '../services/agent.service';
import { Subscription } from 'rxjs';
import { TenantConfigService } from '../../services/tenant-config.service';
import { ThemeService } from '../../services/theme.service';

@Component({
  standalone: false,
  selector: 'app-chat-header',
  templateUrl: './chat-header.component.html',
  styleUrls: ['./chat-header.component.scss']
})
export class ChatHeaderComponent implements OnInit, OnDestroy {
  @Output() toggleSidebar = new EventEmitter<void>();

  agents: Agent[] = [];
  selectedAgentId: number | null = null;
  selectedModel: string | null = null;
  conversationTitle = '';
  activeConversationId: string | null = null;
  isDropdownOpen = false;
  isEditingTitle = false;

  get defaultModels() {
    return [
      { id: 'default', label: this.tenantConfig.tenantInfo.orgName || 'Agent', icon: '🤖', description: 'Default assistant with all tools' },
    ];
  }

  private subs = new Subscription();

  constructor(
    public chatService: ChatService,
    private agentService: AgentService,
    public tenantConfig: TenantConfigService,
    public themeService: ThemeService
  ) {}

  ngOnInit(): void {
    this.agentService.loadAgents();
    // Load capabilities for the initial (default) model so the composer can
    // warn about unsupported attachment types from the first render.
    this.chatService.loadCapabilities(this.selectedModel);

    this.subs.add(
      this.agentService.agents$.subscribe(agents => {
        this.agents = agents.filter(a => a.enabled);
      })
    );

    this.subs.add(
      this.chatService.activeConversationId$.subscribe(id => {
        this.activeConversationId = id;
        if (!id) {
          this.conversationTitle = '';
        }
      })
    );

    this.subs.add(
      this.chatService.conversations$.subscribe(convs => {
        if (this.activeConversationId) {
          const active = convs.find(c => c.conversationId === this.activeConversationId);
          if (active) {
            this.conversationTitle = active.title || 'New conversation';
          }
        }
      })
    );
  }

  get currentLabel(): string {
    if (this.selectedAgentId) {
      const agent = this.agents.find(a => a.agentId === this.selectedAgentId);
      return agent ? agent.name : (this.tenantConfig.tenantInfo.orgName || 'Agent');
    }
    return this.tenantConfig.tenantInfo.orgName || 'Agent';
  }

  toggleDropdown(): void {
    this.isDropdownOpen = !this.isDropdownOpen;
  }

  closeDropdown(): void {
    this.isDropdownOpen = false;
  }

  selectDefault(): void {
    this.selectedAgentId = null;
    this.selectedModel = null;
    this.isDropdownOpen = false;
    this.chatService.setSelection(null, null);
  }

  selectAgent(agent: Agent): void {
    this.selectedAgentId = agent.agentId;
    this.selectedModel = agent.model;
    this.isDropdownOpen = false;
    this.chatService.setSelection(agent.model, agent.agentId);
  }

  startEditTitle(): void {
    if (!this.activeConversationId) return;
    this.isEditingTitle = true;
  }

  saveTitle(): void {
    this.isEditingTitle = false;
    // Title is auto-generated by the backend from the first message
    // Future: PATCH /v1/chat/conversations/:id to update title
  }

  onTitleKeyDown(event: KeyboardEvent): void {
    if (event.key === 'Enter') {
      event.preventDefault();
      this.saveTitle();
    }
    if (event.key === 'Escape') {
      this.isEditingTitle = false;
    }
  }

  newChat(): void {
    this.chatService.newChat();
    this.conversationTitle = '';
  }

  formatTokens(n: number): string {
    if (n >= 1_000_000) return (n / 1_000_000).toFixed(1) + 'M';
    if (n >= 1_000) return (n / 1_000).toFixed(1) + 'k';
    return String(n);
  }

  formatCost(usd: number): string {
    if (usd <= 0) return '';
    if (usd < 0.01) return '<$0.01';
    return '$' + usd.toFixed(usd < 1 ? 3 : 2);
  }

  ngOnDestroy(): void {
    this.subs.unsubscribe();
  }
}
